/**
 * 가상자산 가격·수량 표기 (T028) — 007 FR-040, SC-009, ui-wireframes C4.
 *
 * 시가는 **유효 숫자를 잃지 않게** 보인다 — 1 이상이면 소수 2자리, 1 미만이면 유효 숫자 4자리 이상. SHIB(0.0000053달러)를 소수
 * 2자리로 보이면 `0.00`이 되어 사용자는 시세가 없거나 0이라고 읽는다. 값은 문자열로 다룬다(헌법 원칙 VI) — 반올림하지 않고 자른다.
 */
import { describe, expect, it } from "vitest";
import { formatPrice, formatQuantity } from "@/lib/format";

describe("formatPrice", () => {
  it.each([
    ["7196.39111328125000", "7,196.39"],
    ["84513", "84,513.00"],
    ["1", "1.00"],
    ["1.005", "1.00"],
  ])("1 이상이면 소수 2자리 — %s → %s", (raw, shown) => {
    expect(formatPrice(raw)).toBe(shown);
  });

  it.each([
    ["0.00000579000000", "0.00000579"],
    ["0.00000529999988", "0.000005299"],
    ["0.12345678000000", "0.1234"],
    ["0.5", "0.50"],
    ["0.000000000001", "0.000000000001"],
  ])("1 미만이면 유효 숫자 4자리까지 — %s → %s", (raw, shown) => {
    expect(formatPrice(raw)).toBe(shown);
  });

  it("0이 아닌 가격은 0이나 0.00으로 보이지 않는다", () => {
    for (const raw of ["0.00000529999988", "0.000000000001", "0.0049"]) {
      expect(["0", "0.00"]).not.toContain(formatPrice(raw));
    }
  });
});

describe("formatQuantity", () => {
  it.each([
    ["1.38819719", "1.38819719"],
    ["0.00118206", "0.00118206"],
    ["9990009990009990.00999000", "9,990,009,990,009,990.00999000"],
    ["0.00000000", "0"],
  ])("소수 8자리 그대로, 정수부는 3자리마다 쉼표 — %s → %s", (raw, shown) => {
    expect(formatQuantity(raw)).toBe(shown);
  });
});
