class TestAcquisitionEdges:
    def test_2020년_누진_세율은_비율_넷째_자리_사사오입(self) -> None:
        """7억 → 0.016666… → 0.0167(1.6667%가 아니다). 600,750,000 → 0.01005 → 0.0101(짝수
        반올림이면 0.0100)."""
        assert acquisition_tax(700_000_000, D("2026-10-05"), exceeds_85=False).main == 11_690_000
        assert acquisition_tax(600_750_000, D("2026-10-05"), exceeds_85=False).main == 6_067_570

    def test_6억과_9억_경계(self) -> None:
        on = D("2026-10-05")
        assert acquisition_tax(6 * EOK, on, exceeds_85=False).main == 6_000_000        # 1% 구간
        assert acquisition_tax(6 * EOK + 1, on, exceeds_85=False).main == 6_000_000    # 식 0.0100
        assert acquisition_tax(9 * EOK, on, exceeds_85=False).main == 27_000_000       # 식 0.0300
        assert acquisition_tax(9 * EOK + 1, on, exceeds_85=False).main == 27_000_000   # 3% 구간

    def test_감면기_9억_경계는_이하(self) -> None:
        """2011-03-22 행: 9억 이하 75% 경감(1%), 9억 초과 50%(2%)."""
        on = D("2011-06-15")
        assert acquisition_tax(9 * EOK, on, exceeds_85=False).main == 9_000_000
        assert acquisition_tax(9 * EOK + 100_000, on, exceeds_85=False).main == 18_002_000

    def test_세법_표_앞의_날짜는_계산하지_않는다(self) -> None:
        """2005-12 계약분은 출처에 있지만 세법 표는 2006-01-01부터다 — 가까운 해로 대신하지
        않는다(FR-023)."""
        with pytest.raises(RuleNotCovered):
            acquisition_tax(3 * EOK, D("2005-12-20"), exceeds_85=False)
        with pytest.raises(RuleNotCovered):
            brokerage_fee(3 * EOK, D("2005-12-20"))

    def test_적용한_규칙의_시행일(self) -> None:
        tax = acquisition_tax(3 * EOK, D("2016-05-20"), exceeds_85=False)
        assert tax.rule_from == D("2013-08-28")
        assert brokerage_fee(3 * EOK, D("2021-03-15")).rule_from == D("2015-04-14")


